<?php
/*
 * PHP essentials with TirotirPHP
 *
 * 1. What is PHP?
 *    A server-side scripting language for the web (also usable as a general-purpose language).
 *    The output (usually HTML) is sent to the browser.
 * 2. Server-side vs client-side
 *    PHP runs on the server; HTML, CSS and JavaScript run in the browser.
 * 3. Syntax basics
 *    Code lives between <?php and ?>, statements end with ;, variables start with $.
 * 4. Variables and data types
 *    int, float, string, bool, array, object, null. Types can change at runtime.
 * 5. Control structures
 *    if / elseif / else, switch, match, for, while, do...while, foreach.
 * 6. Functions
 *    Reusable blocks of code; PHP ships with hundreds of built-in functions.
 * 7. Forms and data
 *    Use $_POST and $_GET to read form data. Always validate it.
 * 8. Databases
 *    Use PDO (recommended) or mysqli, and always use prepared statements.
 * 9. Sessions and cookies
 *    Sessions keep data on the server per visitor; cookies store small data in the browser.
 * 10. File handling
 *    fopen, fread, fwrite, file_get_contents, file_put_contents.
 * 11. Security
 *    SQL injection: prepared statements. XSS: escape output with htmlspecialchars. CSRF: tokens.
 * 12. Error handling
 *    try / catch / finally, and error_reporting() for development.
 * 13. PHP with HTML, CSS and JavaScript
 *    PHP can generate HTML dynamically and answer AJAX requests with JSON.
 */

